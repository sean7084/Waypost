@override_settings(MEDIA_ROOT=TEMP_MEDIA)
class ReportParityTests(InspectionFixtureMixin, TestCase):
    """Content parity against real rows from the golden `22149 Gucci SZOL` asset list.

    Validates that the ported transforms reproduce the expected normalized
    categories, In Store status, and cover-page counts for real Kering devices.
    """

    # (category, brand_model, sn, asset_id, usage) sampled from the golden file.
    GOLDEN_ROWS = [
        ('Monitor', 'Lenovo-L1710', '1S60FDHCR1CXU433P8KV', 'GCNLCD0233', 'Xstore'),
        ('Desktop', 'Lenovo-M720Q', 'PC225BDW', 'CGDR-PC225BDW', 'Xstore'),
        ('Scanner', 'Zebra DS2208', '23262010556981', 'CKSO-23262010556981', 'Xstore'),
        ('RFID', 'RFID 8500', '18265523022052', 'GCNRFS0196', 'AR/S2S/PI'),
        ('Printer', 'Epson TM-T88VI', 'X6XX019867', 'CGPR-X6XX019867', 'Xstore'),
        ('iPhone', 'iPhone SE', 'CQ41WPH23K', 'GGCNPH0229', 'AR/S2S/PI'),
    ]

    def _build(self):
        from django.utils import timezone
        inspection = self.make_inspection()
        for index, (category, brand_model, sn, asset_id, usage) in enumerate(self.GOLDEN_ROWS):
            InspectionDevice.objects.create(
                store_inspection=inspection, client_device_uid=f'g-{index}',
                category=category, brand_model=brand_model, sn=sn,
                asset_id_text=asset_id, usage=usage, collected_at=timezone.now(),
            )
        return inspection

    def test_asset_list_rows_and_normalized_categories(self):
        inspection = self._build()
        generate_inspection_report(inspection)
        inspection.refresh_from_db()
        sheet = load_workbook(inspection.report_file.path)['asset_list']
        body = [[cell.value for cell in row] for row in sheet.iter_rows(min_row=2)]
        by_sn = {row[5]: row for row in body if row[5]}
        # Every golden SN is present and reported In Store.
        for _cat, _bm, sn, _aid, _usage in self.GOLDEN_ROWS:
            self.assertIn(sn, by_sn)
            self.assertEqual(by_sn[sn][8], STATUS_IN_STORE)
        # Category normalization: RFID -> AR_Device, iPhone -> IOS_Device.
        self.assertEqual(by_sn['18265523022052'][3], 'AR_Device')
        self.assertEqual(by_sn['CQ41WPH23K'][3], 'IOS_Device')
        self.assertEqual(by_sn['1S60FDHCR1CXU433P8KV'][3], 'Monitor')

    def test_cover_page_counts_match_expected(self):
        inspection = self._build()
        counts = transforms.build_cover_page_summary_counts(list(inspection.devices.all()))
        self.assertEqual(counts['Monitor'], 1)
        self.assertEqual(counts['Xstore PC'], 1)
        self.assertEqual(counts['Xstore Scanner'], 1)
        self.assertEqual(counts['RFID'], 1)
        self.assertEqual(counts['Reception Printer'], 1)
        self.assertEqual(counts['iPhone se（total）'], 1)


